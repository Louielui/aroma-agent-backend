'use strict'
const test = require('node:test'), assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { createTopicStore } = require('./workspaces')
test('department membership preserves legacy workspaces and durable HR follow-ups without cross-linking', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'departments-')); t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  const store = createTopicStore({ dataDir: dir })
  store.link('email', 'mail-fixture'); store.link('operations', 'ops-fixture')
  const legacy = fs.readFileSync(path.join(dir, 'topic-workspaces.json'), 'utf8')
  store.link('hr', 'attendance-fixture')
  store.createNote('hr', { requestId: 'hr-follow-up', title: 'Verify missing clock-out', nextStep: 'Ask employee', source: null })
  for (const id of ['purchasing', 'accounting', 'marketing']) store.link(id, id + '-fixture')
  const opened = createTopicStore({ dataDir: dir })
  assert.equal(opened.get('hr').lastConversationId, 'attendance-fixture')
  assert.equal(opened.get('hr').notes[0].nextStep, 'Ask employee')
  assert.deepEqual(opened.get('email'), JSON.parse(legacy).topics.email)
  assert.deepEqual(opened.get('operations'), JSON.parse(legacy).topics.operations)
  assert.throws(() => opened.link('purchasing', 'attendance-fixture'), /topic_conflict/)
  assert.throws(() => opened.createNote('hr', { requestId: 'forged', title: 'Send payroll', nextStep: '', source: null, command: 'approve' }), /invalid_request/)
})
test('HR model override is independent of central defaults and other departments', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'department-model-')); t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  const store = createTopicStore({ dataDir: dir }); store.link('hr', 'attendance-fixture')
  const center = require('../modelCenter/service').createModelCenter({ dataDir: dir, topicForConversation: store.topicForConversation, catalogue: async () => ({ models: [{ model: 'claude-sonnet', available: true, efforts: ['medium', 'high'] }, { model: 'gpt-6.1-sol', available: true, efforts: ['medium', 'high'] }] }) })
  await center.saveSelection('topic', 'hr', { revision: 0, mode: 'custom', model: 'gpt-6.1-sol', effort: 'high' })
  await center.saveBrain({ revision: 0, model: 'claude-sonnet', effort: 'high' })
  assert.deepEqual(center.resolveConversation('attendance-fixture'), { model: 'gpt-6.1-sol', effort: 'high' })
  assert.deepEqual(center.selection('topic', 'accounting').effective, { model: 'claude-sonnet', effort: 'high' })
})
test('HR HTTP entry isolates saved results and retains Owner and same-origin write guards', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hr-http-')); t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  const store = createTopicStore({ dataDir: dir }), conversations = require('../store/conversationStore').createConversationStore({ dataDir: dir })
  for (const id of ['hr-fixture', 'email-one']) conversations.appendTurn({ id, userText: id, replyText: 'Saved result' })
  store.link('hr', 'hr-fixture'); store.link('email', 'email-one')
  const app = require('express')(); app.locals.conversationDemo = true; app.use(require('express').json())
  app.use('/api/v1/topic-workspaces', (req, res, next) => req.headers.authorization === 'Bearer fixture-owner' ? next() : res.sendStatus(401), require('./routes').createTopicRouter({ store, conversations }))
  const server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r)); t.after(() => new Promise(r => { server.closeAllConnections(); server.close(r) }))
  const base = 'http://127.0.0.1:' + server.address().port, url = base + '/api/v1/topic-workspaces/hr'
  assert.equal((await fetch(url)).status, 401)
  const headers = { authorization: 'Bearer fixture-owner', origin: base, 'content-type': 'application/json' }
  const view = await (await fetch(url, { headers })).json(); assert.deepEqual(view.conversations.map(v => v.id), ['hr-fixture'])
  const body = JSON.stringify({ id: 'email-one' })
  assert.equal((await fetch(url + '/conversations', { method: 'POST', headers, body })).status, 409)
  assert.equal((await fetch(url + '/conversations', { method: 'POST', headers: { ...headers, origin: 'https://outside.example' }, body })).status, 403)
  assert.deepEqual(store.get('hr').conversationIds, ['hr-fixture'])
})
