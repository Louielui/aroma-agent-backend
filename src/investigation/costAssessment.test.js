test('cost findings lead with bilingual assessment and source-bound read-only next steps',()=>{
 const r=report([section('execution',[call('one')]),section('billing',[],'unconnected')])
 for(const message of ['哪些工作消耗額度？','Which jobs consume quota?']){
  const view=renderCostFindings(r,{message})
  assert.match(view.text.split('\n')[0],/成本調查結論|Cost investigation conclusion/)
  assert.match(view.text,/帳戶額度消耗.*未確認|account quota consumption.*not confirmed/)
  assert.doesNotMatch(view.text,/⟦\?/)
  assert.match(view.text,/補查建議|read-only follow-up recommendations/)
  assert.ok(view.references.some(x=>x.recordId==='invocation:one'))
 }
 assert.ok(r.costAssessment.recommendations.every(x=>x.readOnly===true))
 assert.equal(r.costAssessment.inventoryComplete,false)
})
test('canonical worker record is not counted twice and different worker kinds stay separate',()=>{
 const trace={workId:'work:'+require('node:crypto').createHash('sha256').update(JSON.stringify(['worker/project-runs',request])).digest('hex'),recordId:request,runId:'22345678-1234-4234-8234-123456789012',kind:'project-runs',attempt:1}
 const row={sourceId:request,kind:'worker/project-runs',state:'completed',workerRuns:[{trace,state:'completed'}]}
 const r=report([section('execution',[call('worker',{role:'worker_completion',workerTrace:trace,linkBasis:'host_worker_identity'})]),section('work',[row])])
 assert.equal(r.executionUsage.chains.length,2)
 assert.equal(r.costAssessment.jobs.length,1)
 assert.equal(r.costAssessment.jobs[0].kind,'worker_work')
 assert.equal(r.costAssessment.summary.exactJobs,1)
 const other=report([section('execution',[call('worker',{workerTrace:trace,linkBasis:'host_worker_identity'})]),section('work',[{...row,kind:'worker/project-tasks'}])])
 assert.equal(other.costAssessment.jobs.length,2)
})
test('fresh activity uses configured model; conflicts cannot confirm current activity',()=>{
 const row={sourceId:'backend:mail_analysis',role:'mail_analysis',configuredModel:'claude-sonnet-5-5',model:'claude-opus-5-5',modelBasis:'in_flight_request_selection',enabled:true,currentRunningState:'active',evidenceBasis:'live_process_snapshot',at}
 const r=report([section('configuration',[row])])
 assert.equal(r.costAssessment.activities[0].configuredModel.value,'claude-sonnet-5-5')
 assert.equal(r.costAssessment.activities[0].running.value,'active')
 const conflict=report([section('configuration',[row,{...row,currentRunningState:'idle'}])])
 assert.equal(conflict.costAssessment.activities.length,1)
 assert.equal(conflict.costAssessment.activities[0].running.value,null)
 assert.equal(conflict.costAssessment.activities[0].running.state,'UNKNOWN')
 for(const currentRunningState of ['disabled','not_installed']){
  const stopped=report([section('schedules',[{sourceId:'task',currentRunningState,executionKind:'deterministic_food_recall_check',usesModel:false,scheduled:false,at}])])
  const view=renderCostFindings(stopped,{message:'Which jobs consume quota?'})
  assert.match(view.text,new RegExp(currentRunningState==='disabled'?'disabled':'not installed'))
  assert.match(view.text,/no model used/)
 }
})
