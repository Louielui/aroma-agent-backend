'use strict'
const test=require('node:test'),assert=require('node:assert/strict')
const {evaluateInvestigation}=require('./intelligence')
const {renderCostFindings}=require('./costFindings')
const at='2026-10-09T14:00:00Z',request='12345678-1234-4234-8234-123456789012'
const call=(id,extra={})=>({sourceId:'invocation:'+id,invocationId:id,requestId:request,linkBasis:'host_request_identity',role:'chat_completion',phase:'answer',state:'succeeded',startedAt:at,finishedAt:'2026-10-09T14:00:01Z',actualModel:'claude-opus-5-5',modelResultObserved:true,billingRoute:'claude-subscription',usageBasis:'provider_result_model_usage',usage:{inputTokens:10,outputTokens:4},evidenceBasis:'owner_bridge_invocation_ledger',...extra})
const section=(name,records,state='partial')=>({section:name,sourceId:name+':fixture',retrievedAt:at,state,records})
const report=sections=>evaluateInvestigation({focus:'cost',sections})
test('real read adapter feeds a distinct job, usage, account and billing assessment',async()=>{
 const adapter=require('../context/adapters/xiangxiangOperationsRead').createXiangxiangOperationsReadAdapter({dataDir:__dirname,executionReader:async()=>({state:'ok',records:[]}),invocationReader:async()=>({state:'partial',records:[call('one')],retained:1,omitted:0,coverageStartedAt:at})})
 const snapshot=await adapter.methods.readInvestigation({sections:['execution','billing']})
 const r=report(snapshot.results.map(x=>({sourceId:x.sourceId,retrievedAt:x.retrievedAt,...x.fields})))
 assert.equal(r.costAssessment.jobs[0].usage.state,'CONFIRMED')
 assert.equal(r.costAssessment.jobs[0].usage.completeJob,false)
 assert.equal(r.costAssessment.jobs[0].billing.amount,null)
 assert.equal(r.costAssessment.jobs[0].accountQuotaConsumption.state,'UNKNOWN')
 assert.equal(r.costAssessment.sources.find(s=>s.key==='claude_quota').state,'UNAVAILABLE')
 assert.ok(r.costAssessment.jobs[0].references.some(r=>r.recordId==='invocation:one'))
})
