
'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const os=require('node:os')
const path=require('node:path')
const {makeSpool, signed, readSigned, transport}=require('./experiment')
const keys='12'.repeat(32)
const boot='ab'.repeat(16)
async function using(t) {
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'xx-p1-'))
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}))
  return makeSpool(root,keys)
}
test('refuses an unattested or stale guest without queueing a chat',async t=>{
  const spool=await using(t)
  const relay=transport(spool,{timeoutMs:300,pollMs:20})
  assert.equal(relay.ready(),false)
  await assert.rejects(relay.call('chat',{profile:'B',message:'abc',history:[]}),/experiment_offline/)
  fs.writeFileSync(path.join(spool.output,'ready.json'),JSON.stringify(signed('00'.repeat(32),{boot,at:Date.now(),network:'ENETUNREACH'})))
  assert.equal(relay.ready(),false)
  fs.writeFileSync(path.join(spool.output,'ready.json'),JSON.stringify(signed(keys,{boot,at:Date.now()-60000,network:'ENETUNREACH'})))
  assert.equal(relay.ready(),false)
  assert.deepEqual(fs.readdirSync(spool.input),[])
})
test('correlates guest epoch, request, actual model and raw response, and does not retry',async t=>{
  const spool=await using(t)
  const relay=transport(spool,{timeoutMs:500,pollMs:20})
  fs.writeFileSync(path.join(spool.output,'ready.json'),JSON.stringify(signed(keys,{boot,at:Date.now(),network:'ENETUNREACH'})))
  const pending=relay.call('chat',{profile:'B',message:'abc',history:[]})
  const [file]=fs.readdirSync(spool.input)
  const req=readSigned(path.join(spool.input,file),keys)
  assert.equal(req.boot,boot)
  assert.equal(req.body.profile,'B')
  await assert.rejects(relay.call('release',{}),/experiment_busy/)
  const response={id:req.id,boot,result:{profile:'P',model:'qwen3.8:27b',engine:'ollama',architecture:'B',calls:1,text:'wrong'}}
  fs.writeFileSync(path.join(spool.output,file),JSON.stringify(signed(keys,response)))
  await assert.rejects(pending,/experiment_model_mismatch/)
  assert.deepEqual(fs.readdirSync(spool.input),[])
})
